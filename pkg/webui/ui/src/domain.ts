import { sha256 } from "js-sha256"
import type {
  CommandResultSummary,
  DriftDetectionResult,
  KluctlDeploymentInfo,
  ObjectRef,
  ProjectKey,
  TargetKey,
  ValidateResult,
  ValidateResultSummary,
} from "./models"

export type Manifest = Record<string, unknown> & {
  metadata?: { annotations?: Record<string, string>; managedFields?: unknown }
  status?: unknown
}

type Condition = {
  type: string
  status: string
  reason?: string
  message?: string
  lastTransitionTime?: string
}
export type RequestKind = "reconcile" | "validate" | "deploy" | "prune"
type RequestResult = {
  request?: { requestValue: string }
  startTime?: string
  endTime?: string
  resultId?: string
  commandError?: string
  reconcileId?: string
}
export type Deployment = Manifest & {
  metadata: { uid: string; name: string; namespace: string }
  spec: Record<string, unknown> & {
    source?: Source & { git?: Source; oci?: Source }
    target?: string
    targetNameOverride?: string
    suspend?: boolean
    dryRun?: boolean
    validate?: boolean
    manual?: boolean
    manualObjectsHash?: string
  }
  status?: Partial<Record<`${RequestKind}RequestResult`, RequestResult>> & {
    projectKey?: ProjectKey
    targetKey?: TargetKey
    conditions?: Condition[]
    lastPrepareError?: string
    lastObjectsHash?: string
    lastDeployResult?: CommandResultSummary
    lastValidateResult?: ValidateResult
    lastDriftDetectionResult?: DriftDetectionResult
    lastDriftDetectionResultMessage?: string
  }
}
type Source = { url?: string; path?: string; ref?: Record<string, string> }

export type DeploymentEventData = { deployment: Deployment; clusterId: string }
export type Event =
  | { type: "update_command_result_summary"; summary: CommandResultSummary }
  | { type: "update_validate_result_summary"; summary: ValidateResultSummary }
  | ({ type: "update_kluctl_deployment" } & DeploymentEventData)
  | {
      type:
        | "delete_command_result_summary"
        | "delete_validate_result_summary"
        | "delete_kluctl_deployment"
      id: string
      clusterId?: string
    }

export function emptyInventory() {
  return {
    commands: new Map<string, CommandResultSummary>(),
    validations: new Map<string, ValidateResultSummary>(),
    deployments: new Map<string, DeploymentEventData>(),
  }
}
export type Inventory = ReturnType<typeof emptyInventory>

export function applyEvents(inventory: Inventory, events: Event[]): Inventory {
  const next = {
    commands: new Map(inventory.commands),
    validations: new Map(inventory.validations),
    deployments: new Map(inventory.deployments),
  }
  for (const event of events) {
    switch (event.type) {
      case "update_command_result_summary":
        next.commands.set(event.summary.id, event.summary)
        break
      case "delete_command_result_summary":
        next.commands.delete(event.id)
        break
      case "update_validate_result_summary":
        next.validations.set(event.summary.id, event.summary)
        break
      case "delete_validate_result_summary":
        next.validations.delete(event.id)
        break
      case "update_kluctl_deployment":
        next.deployments.set(event.deployment.metadata.uid, event)
        break
      case "delete_kluctl_deployment":
        next.deployments.delete(event.id)
        break
    }
  }
  return next
}

const sortedJson = (obj: unknown) =>
  JSON.stringify(obj, (_key, value: unknown) =>
    value && typeof value === "object" && !Array.isArray(value)
      ? Object.fromEntries(
          Object.entries(value).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        )
      : value
  )

export function targetId(
  project: ProjectKey,
  target: TargetKey,
  kluctlDeployment?: KluctlDeploymentInfo
) {
  // Keep links generated by older Kluctl versions working.
  return sha256(sortedJson({ project, target, kluctlDeployment }))
}

export const deploymentId = (instance: KluctlDeploymentInfo) =>
  `deployment-${sha256(sortedJson(instance))}`

export function deploymentSource(deployment: Deployment) {
  const source = deployment.spec.source
  return source?.git ?? source?.oci ?? source
}

// Best-effort display identity until the controller reports its canonical key.
// Never use this to resolve a run or assume where the deployment will run.
function sourceProject(deployment: Deployment): ProjectKey {
  const source = deploymentSource(deployment)
  const subDir = source?.path?.replace(/^\.\/|\/$/g, "")
  const raw = source?.url
  if (raw) {
    const url = raw.replace(/^(?:[^/@:]+@)?([^/:]+):([^/].*)$/, "ssh://$1/$2")
    try {
      const { protocol, host, pathname } = new URL(url)
      if (host && pathname.length > 1) {
        const kind = protocol === "oci:" ? "oci" : "git"
        const path = pathname.replace(/^\/|\/$/g, "")
        return {
          repoKey: `${kind}://${host}/${kind === "git" ? path.replace(/\.git$/, "") : path}`,
          subDir,
        }
      }
    } catch {
      // The controller will report an invalid or missing source separately.
    }
  }
  return { subDir }
}

export type TargetRow = {
  id: string
  project: ProjectKey
  target: TargetKey
  instance?: KluctlDeploymentInfo
  deployment?: Deployment
  runs: CommandResultSummary[]
  validation?: ValidateResultSummary
}

const time = (value?: string) => Date.parse(value ?? "") || 0
const newest = (a?: string, b?: string) =>
  time(b) - time(a) || (b ?? "").localeCompare(a ?? "")

export function targetsFrom({
  commands,
  validations,
  deployments,
}: Inventory): TargetRow[] {
  const indexed = new Map<string, TargetRow>()
  const known = new Set<string>()
  function get(
    project: ProjectKey,
    target: TargetKey,
    instance?: KluctlDeploymentInfo
  ) {
    const id = targetId(project, target, instance)
    let row = indexed.get(id)
    if (!row) {
      row = { id, project, target, instance, runs: [] }
      indexed.set(id, row)
    }
    return row
  }
  for (const { deployment, clusterId } of deployments.values()) {
    const { projectKey, targetKey } = deployment.status ?? {}
    const instance = {
      clusterId,
      name: deployment.metadata.name,
      namespace: deployment.metadata.namespace,
    }
    known.add(sortedJson(instance))
    if (projectKey && targetKey) {
      get(projectKey, targetKey, instance).deployment = deployment
    } else {
      const id = deploymentId(instance)
      indexed.set(id, {
        id,
        project: projectKey ?? sourceProject(deployment),
        target: targetKey ?? {
          clusterId: "",
          targetName:
            deployment.spec.targetNameOverride || deployment.spec.target,
        },
        instance,
        deployment,
        runs: [],
      })
    }
  }
  for (const run of commands.values()) {
    if (run.kluctlDeployment && !known.has(sortedJson(run.kluctlDeployment)))
      continue
    get(run.projectKey, run.targetKey, run.kluctlDeployment).runs.push(run)
  }
  for (const validation of validations.values()) {
    const row = indexed.get(
      targetId(
        validation.projectKey,
        validation.targetKey,
        validation.kluctlDeployment
      )
    )
    if (
      row &&
      (!row.validation ||
        newest(validation.startTime, row.validation.startTime) < 0)
    )
      row.validation = validation
  }
  const rows = Array.from(indexed.values())
  for (const row of rows) {
    row.runs.sort(
      (a, b) =>
        newest(a.commandInfo?.startTime, b.commandInfo?.startTime) ||
        newest(a.commandInfo?.endTime, b.commandInfo?.endTime) ||
        (b.commandInfo?.command ?? "").localeCompare(
          a.commandInfo?.command ?? ""
        ) ||
        a.id.localeCompare(b.id)
    )
  }
  return rows.sort(
    (a, b) =>
      (a.project.repoKey ?? "").localeCompare(b.project.repoKey ?? "") ||
      (a.project.subDir ?? "").localeCompare(b.project.subDir ?? "") ||
      (a.target.targetName ?? "").localeCompare(b.target.targetName ?? "") ||
      a.target.clusterId.localeCompare(b.target.clusterId) ||
      (a.target.discriminator ?? "").localeCompare(
        b.target.discriminator ?? ""
      ) ||
      a.id.localeCompare(b.id)
  )
}

export const requestKinds: RequestKind[] = [
  "reconcile",
  "validate",
  "deploy",
  "prune",
]
export function requestState(deployment: Deployment, kind: RequestKind) {
  const result = deployment.status?.[`${kind}RequestResult`]
  const annotation =
    deployment.metadata.annotations?.[`kluctl.io/request-${kind}`]
  let requested: string | undefined
  if (annotation) {
    try {
      requested = JSON.parse(annotation).requestValue
    } catch {
      /* ignore invalid request annotations */
    }
  }
  const state =
    requested && requested !== result?.request?.requestValue
      ? "Requested"
      : result && !result.endTime
        ? "Running"
        : result?.commandError
          ? "Failed"
          : result?.endTime
            ? "Completed"
            : "Not requested"
  return { state, result }
}

const readyCondition = (deployment?: Deployment) =>
  deployment?.status?.conditions?.find((c) => c.type === "Ready")

// The controller also emits Ready=False before the first deploy (for example
// on a suspended deployment or one waiting for manual approval).
const waitingForFirstDeploy = (condition?: Condition) =>
  condition?.reason === "DeployFailed" &&
  condition.message === "deployment status unknown"

export function reconciliation(row: TargetRow) {
  if (!row.deployment)
    return {
      label: row.instance ? "Historical target" : "—",
      tone: "muted",
    } as const
  const { spec, status } = row.deployment
  const ready = readyCondition(row.deployment)
  const running = status?.conditions?.find(
    (c) => c.type === "Reconciling" && c.status === "True"
  )
  if (spec.suspend)
    return { label: "Suspended", tone: "muted", condition: ready } as const
  if (
    running ||
    requestKinds.some(
      (kind) => requestState(row.deployment!, kind).state === "Running"
    )
  )
    return { label: "Reconciling", tone: "info", condition: running } as const
  if (
    requestKinds.some(
      (kind) => requestState(row.deployment!, kind).state === "Requested"
    )
  )
    return { label: "Requested", tone: "info", condition: ready } as const
  if (ready?.status === "True" || ready?.reason === "ValidateFailed")
    return { label: "Ready", tone: "good", condition: ready } as const
  if (
    status?.lastPrepareError ||
    (ready?.status === "False" && !waitingForFirstDeploy(ready))
  )
    return {
      label: status?.lastPrepareError ? "Prepare failed" : "Not ready",
      tone: "bad",
      condition: ready,
    } as const
  return { label: "Unknown", tone: "muted", condition: ready } as const
}

export function validationOf(row: TargetRow) {
  if (row.deployment && !row.deployment.spec.validate) return undefined
  if (row.validation) return row.validation
  // The embedded result can be available even if the detail wasn't retained
  // in the result store (or the UI is reading a snapshot).
  const value = row.deployment?.status?.lastValidateResult
  return (
    value && {
      ready: value.ready,
      errors: value.errors?.length ?? 0,
      warnings: value.warnings?.length ?? 0,
      startTime: value.startTime,
    }
  )
}

export function validationStatus(row: TargetRow) {
  const value = validationOf(row)
  if (!value && !row.deployment?.spec.validate)
    return { label: "Off", tone: "muted" } as const
  if (!value) return { label: "No result", tone: "muted" } as const
  if (!value.ready || value.errors)
    return { label: "Not ready", tone: "bad" } as const
  if (value.warnings) return { label: "Warnings", tone: "warn" } as const
  return { label: "Ready", tone: "good" } as const
}

export const driftOf = (row: TargetRow) =>
  row.deployment?.status?.lastDriftDetectionResult

export function approvalOf(row: TargetRow) {
  const spec = row.deployment?.spec
  const drift = driftOf(row)
  const hash = drift?.renderedObjectsHash
  if (!spec?.manual || spec.dryRun || !hash || !drift?.objects?.length) return
  return { hash, required: spec.manualObjectsHash !== hash }
}

export function targetSignals(row: TargetRow) {
  const latest = row.runs[0] ?? row.deployment?.status?.lastDeployResult
  const drift = driftOf(row)
  const validation = validationOf(row)
  const ready = readyCondition(row.deployment)
  const hasControllerError =
    !!row.deployment?.status?.lastPrepareError ||
    (ready?.status === "False" && !waitingForFirstDeploy(ready))
  const errors =
    (latest?.errors?.length ?? 0) +
    Math.max(validation?.errors ?? 0, Number(validation?.ready === false)) +
    (drift?.errors?.length ?? 0)
  return {
    drift: drift?.objects?.length ?? 0,
    errors: errors || Number(hasControllerError),
    warnings:
      (latest?.warnings?.length ?? 0) +
      (validation?.warnings ?? 0) +
      (drift?.warnings?.length ?? 0),
  }
}

export function runOutcome(run: CommandResultSummary) {
  return run.errors?.length
    ? "Errors"
    : run.warnings?.length
      ? "Warnings"
      : run.newObjects ||
          run.changedObjects ||
          run.orphanObjects ||
          run.deletedObjects ||
          run.totalChanges
        ? "Changes"
        : "No changes"
}

export function findTargetById(rows: TargetRow[], id?: string) {
  return (
    rows.find((row) => row.id === id) ??
    (id?.startsWith("deployment-")
      ? rows.find(
          (row) =>
            row.deployment && row.instance && deploymentId(row.instance) === id
        )
      : undefined)
  )
}

export const targetPath = (row: TargetRow) => `/targets/${row.id}`
export const historyPath = (row: TargetRow, run?: string) =>
  `${targetPath(row)}/results${run ? `/${encodeURIComponent(run)}` : ""}`
export const refKey = (ref: ObjectRef) =>
  JSON.stringify([
    ref.group ?? "",
    ref.version ?? "",
    ref.kind,
    ref.namespace ?? "",
    ref.name,
  ])
export const refLabel = (ref?: ObjectRef) =>
  ref?.kind
    ? `${ref.kind} ${ref.namespace ? `${ref.namespace}/` : ""}${ref.name}`
    : "General"

export function findLinkedTarget(rows: TargetRow[], params: URLSearchParams) {
  const runId = params.get("commandResultId")
  if (runId) {
    const row = rows.find((row) => row.runs.some((run) => run.id === runId))
    return row && historyPath(row, runId)
  }
  const keys = [
    "repoKey",
    "subDir",
    "targetName",
    "targetClusterId",
    "discriminator",
    "kluctlDeploymentName",
    "kluctlDeploymentNamespace",
    "kluctlDeploymentClusterId",
  ]
  if (!keys.some((key) => params.has(key))) return "/targets"
  const matches = rows.filter(({ project, target, instance }) => {
    const values = [
      project.repoKey,
      project.subDir,
      target.targetName,
      target.clusterId,
      target.discriminator,
      instance?.name,
      instance?.namespace,
      instance?.clusterId,
    ]
    return keys.every(
      (key, i) => !params.has(key) || params.get(key) === values[i]
    )
  })
  const row = matches.find(({ deployment }) => deployment) ?? matches[0]
  return row && targetPath(row)
}
